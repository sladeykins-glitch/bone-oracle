import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const core=fs.readFileSync(path.join(root,'core.js'),'utf8').replace(/^export /gm,'');
const handler=fs.readFileSync(path.join(root,'worker-handler.js'),'utf8');
const output='// Bone Oracle v3 Worker. Generated by node scripts/build-worker.mjs.\n// Paste this entire self-contained file into Cloudflare, or deploy with Wrangler.\n// Keys are Cloudflare secrets; never add them to this repository.\n'+core+'\n'+handler;
const destination=path.join(root,'cloudflare-worker.js');
if(process.argv.includes('--check')){if(fs.readFileSync(destination,'utf8')!==output){console.error('Worker bundle is stale. Run npm run build:worker.');process.exit(1);}console.log('Worker bundle matches the tested rules and handler.');}else{fs.writeFileSync(destination,output);console.log('Built self-contained Cloudflare Worker.');}
